// @vitest-environment jsdom
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import { cleanup, render, screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { App } from '../src/ui/App'
import { LessonCourse } from '../src/ui/LessonCourse'
import { loadProgress, defaultProgress, saveProgress } from '../src/core/storage'

beforeEach(() => localStorage.clear())
afterEach(cleanup)
const stored = () => loadProgress(localStorage)
async function enterPractice(user: ReturnType<typeof userEvent.setup>) {
  await user.click(screen.getByRole('button', { name: '新手课堂' }))
  await user.click(screen.getByRole('button', { name: '开始原局面练习' }))
}
async function move(user: ReturnType<typeof userEvent.setup>, from: string, to: string) {
  await user.click(screen.getByRole('button', { name: new RegExp(from) }))
  await user.click(screen.getByRole('button', { name: new RegExp(to) }))
}
async function firstChallenge(user: ReturnType<typeof userEvent.setup>) {
  await enterPractice(user)
  await move(user, '红兵，坐标 0,6', '交叉点 0,5.*可走落点')
  await user.click(screen.getByRole('button', { name: '进入未见变式' }))
}

describe('beginner course stages', { timeout: 20000 }, () => {
  it.each([['stalemate', '困毙'], ['unknown-unit', '交叉点与轮流行棋']] as const)('starts a requested knowledge point or safely falls back for %s', (initialUnitId, title) => {
    render(<LessonCourse initialUnitId={initialUnitId} progress={defaultProgress()} onProgress={() => {}} onTerm={() => {}} onPracticeAi={() => {}} />)
    expect(screen.getByRole('heading', { name: title })).toBeTruthy()
    expect(screen.getByText('演示 · 先看一遍')).toBeTruthy()
  })

  it('keeps demonstration separate from practice and records mastery only on a new unassisted variant', async () => {
    const user = userEvent.setup()
    render(<App />)
    await user.click(screen.getByRole('button', { name: '新手课堂' }))
    expect(screen.getByText('演示 · 先看一遍')).toBeTruthy()
    await user.click(screen.getByRole('button', { name: '演示这一步' }))
    expect(screen.getByRole('button', { name: /红兵，坐标 0,5.*上一步/ })).toBeTruthy()
    expect(screen.getByText('当前棋盘：黑方行棋')).toBeTruthy()
    expect(stored().practicedUnits).toEqual([])
    await user.click(screen.getByRole('button', { name: '开始原局面练习' }))
    expect(screen.getByRole('button', { name: '红兵，坐标 0,6' })).toBeTruthy()
    await move(user, '红兵，坐标 0,6', '交叉点 0,5.*可走落点')
    expect(stored().practicedUnits).toEqual(['turns'])
    expect(stored().masteredUnits).toEqual([])
    await user.click(screen.getByRole('button', { name: '进入未见变式' }))
    expect(screen.getByText('挑战 · 未见变式')).toBeTruthy()
    expect(screen.queryByRole('button', { name: /红兵，坐标 0,5/ })).toBeNull()
    await move(user, '黑卒，坐标 2,3', '交叉点 2,4.*可走落点')
    expect(stored().masteredUnits).toEqual(['turns'])
    expect(stored().completedLessons).toEqual([])
    await user.click(screen.getByRole('button', { name: '开始对弈' }))
    expect(screen.getByText('红方行棋')).toBeTruthy()
  })

  it('persists hint exposure immediately and cannot upgrade a repeated assisted question', async () => {
    const user = userEvent.setup()
    render(<App />)
    await firstChallenge(user)
    await user.click(screen.getByRole('button', { name: '提示 1 · 观察' }))
    expect(stored().assistedVariants).toEqual(['turns-variant-1'])
    await user.click(screen.getByRole('button', { name: '提示 2 · 规则与思路' }))
    await user.click(screen.getByRole('button', { name: '提示 3 · 具体着法或答案' }))
    expect(screen.getByText(/示范着法：卒3进1/)).toBeTruthy()
    expect(screen.getByRole('button', { name: '三层提示已展开' }).hasAttribute('disabled')).toBe(true)
    await user.click(screen.getByRole('button', { name: '重试本题' }))
    await move(user, '黑卒，坐标 2,3', '交叉点 2,4.*可走落点')
    expect(stored().masteredUnits).toEqual([])
    expect(screen.getByRole('status').textContent).toContain('只记练习')
    await user.click(screen.getByRole('button', { name: '换一个未见变式' }))
    await move(user, '红兵，坐标 6,6', '交叉点 6,5.*可走落点')
    expect(stored().masteredUnits).toEqual(['turns'])
  })

  it('skips exposed variants after refresh and labels exhausted questions as practice', async () => {
    const user = userEvent.setup()
    render(<App />)
    await firstChallenge(user)
    await user.click(screen.getByRole('button', { name: '揭晓答案' }))
    expect(stored().assistedVariants).toEqual(['turns-variant-1'])
    cleanup()
    render(<App />)
    await firstChallenge(user)
    expect(screen.getByRole('button', { name: '红兵，坐标 6,6' })).toBeTruthy()
    await user.click(screen.getByRole('button', { name: '揭晓答案' }))
    await user.click(screen.getByRole('button', { name: '换一个变式练习' }))
    expect(screen.getByText('变式练习 · 已见题目')).toBeTruthy()
    await move(user, '黑卒，坐标 2,3', '交叉点 2,4.*可走落点')
    expect(stored().masteredUnits).toEqual([])
  })

  it('supports choices, chapter and unit jumps, and labels legacy completion separately', async () => {
    const user = userEvent.setup()
    saveProgress(localStorage, { ...defaultProgress(), completedLessons: ['finish'] })
    render(<App />)
    await user.click(screen.getByRole('button', { name: '新手课堂' }))
    await user.click(screen.getByRole('button', { name: /06 · 将死与困毙/ }))
    expect(screen.getByText('旧版已完成')).toBeTruthy()
    await user.click(screen.getByRole('button', { name: /^困毙与两类和棋/ }))
    await user.click(screen.getByRole('button', { name: '开始原局面练习' }))
    await user.click(screen.getByRole('button', { name: '困毙：无合法着法的一方负' }))
    expect(screen.getByRole('status').textContent).toContain('终局原因')
    expect(stored().practicedUnits).toEqual([])
    await user.click(screen.getByRole('button', { name: '双方同意和棋' }))
    await user.click(screen.getByRole('button', { name: '进入未见变式' }))
    await user.click(screen.getByRole('button', { name: '困毙：无合法着法的一方负' }))
    expect(stored().masteredUnits).toEqual(['draws'])
    await user.click(screen.getByRole('button', { name: '换一个未见变式' }))
    expect(screen.getByText('连续未吃子：120 着')).toBeTruthy()
    await user.click(screen.getByRole('button', { name: '长期无吃子达到自然限着，和棋' }))
    expect(screen.getByRole('status').textContent).toContain('自然限着')
  })

  it('cycles all exposed variants for review after reloading without granting mastery', async () => {
    const user = userEvent.setup()
    saveProgress(localStorage, { ...defaultProgress(), assistedVariants: ['draws-variant-1', 'draws-variant-2'] })
    render(<App />)
    await user.click(screen.getByRole('button', { name: '新手课堂' }))
    await user.click(screen.getByRole('button', { name: /06 · 将死与困毙/ }))
    await user.click(screen.getByRole('button', { name: /^困毙与两类和棋/ }))
    await user.click(screen.getByRole('button', { name: '开始原局面练习' }))
    await user.click(screen.getByRole('button', { name: '双方同意和棋' }))
    await user.click(screen.getByRole('button', { name: '开始变式复习' }))
    expect(screen.getByText('变式练习 · 已见题目')).toBeTruthy()
    await user.click(screen.getByRole('button', { name: '换一个变式练习' }))
    expect(screen.getByText('连续未吃子：120 着')).toBeTruthy()
    await user.click(screen.getByRole('button', { name: '长期无吃子达到自然限着，和棋' }))
    expect(stored().masteredUnits).toEqual([])
    await user.click(screen.getByRole('button', { name: '换一个变式练习' }))
    expect(screen.queryByText('连续未吃子：120 着')).toBeNull()
    await user.click(screen.getByRole('button', { name: '困毙：无合法着法的一方负' }))
    expect(stored().masteredUnits).toEqual([])
  })

  it('uses rule and goal feedback without changing a mistaken position and accepts multiple correct moves', async () => {
    const user = userEvent.setup()
    render(<App />)
    await enterPractice(user)
    await move(user, '红兵，坐标 0,6', '交叉点 0,4')
    expect(screen.getByRole('status').textContent).toContain('不能走到这里')
    expect(screen.getByRole('button', { name: /红兵，坐标 0,6/ })).toBeTruthy()
    await user.click(screen.getByRole('button', { name: /08 · 开局第一步/ }))
    await user.click(screen.getByRole('button', { name: '开始原局面练习' }))
    await move(user, '红兵，坐标 0,6', '交叉点 0,5.*可走落点')
    expect(screen.getByRole('status').textContent).toContain('未实现')
    expect(screen.getByRole('button', { name: /红兵，坐标 0,6/ })).toBeTruthy()
    await move(user, '红兵，坐标 6,6', '交叉点 6,5.*可走落点')
    await user.click(screen.getByRole('button', { name: '进入未见变式' }))
    await move(user, '黑马，坐标 7,0', '交叉点 6,2.*可走落点')
    expect(stored().masteredUnits).toContain('opening-move')
  })

  it.each([['带提示下第一盘', true], ['自己下第一盘', false]] as const)('starts a standard learning match via %s', async (label, coachEnabled) => {
    const user = userEvent.setup()
    render(<App />)
    await user.click(screen.getByRole('button', { name: '新手课堂' }))
    await user.click(screen.getByRole('button', { name: /08 · 开局第一步/ }))
    await user.click(screen.getByRole('button', { name: label }))
    expect(screen.getByRole('heading', { name: '人机练习' })).toBeTruthy()
    expect(stored().learningMatch).toMatchObject({ active: true, standardStart: true, coachEnabled, coachEverUsed: coachEnabled })
    expect(stored().session.records).toHaveLength(0)
  })

  it('retains the cannon flat move as a reference on the same demonstration board', async () => {
    const user = userEvent.setup()
    render(<App />)
    await user.click(screen.getByRole('button', { name: '新手课堂' }))
    await user.click(screen.getByRole('button', { name: /02 · 车马炮/ }))
    await user.click(screen.getByRole('button', { name: /^炮架/ }))
    await user.click(screen.getByRole('button', { name: '炮二平五：炮平走' }))
    expect(screen.getByRole('button', { name: /红炮，坐标 4,7.*上一步/ })).toBeTruthy()
    expect(screen.getAllByRole('group', { name: '象棋棋盘' })).toHaveLength(1)
    expect(stored().practicedUnits).toEqual([])
  })
})
