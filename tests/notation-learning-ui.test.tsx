import { useEffect, useState } from 'react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { act, cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { notationUnits } from '../src/content/notation-lessons'
import type { MoveTask } from '../src/content/curriculum'
import { defaultProgress, loadProgress, saveProgress } from '../src/core/storage'
import type { Progress } from '../src/core/storage'
import { LessonCourse } from '../src/ui/LessonCourse'
import { NotationLearningGuide } from '../src/ui/NotationLearningGuide'

beforeEach(() => localStorage.clear())
afterEach(cleanup)
const files = notationUnits[0]
const cell = (x: number, y: number) => screen.getByRole('button', { name: new RegExp(`(?:坐标 |交叉点 )${x},${y}(?:，|$)`) })
const status = () => screen.getByRole('status').textContent
const flip = () => screen.getByRole('button', { name: '翻转本题视角' })
const table = () => screen.queryByRole('table', { name: '双方路数（屏幕从左到右）' })
const rows = () => within(table()!).getAllByRole('row').map(row => within(row).getAllByRole('cell').map(value => value.textContent))

function mountCourse(unitId = files.id, initial = defaultProgress()) {
  let latest = initial
  let replaceProgress: (value: Progress) => void = () => {}
  const writes = vi.fn()
  function Harness({ navigation, hidden = false }: { navigation?: { unitId: string; sequence: number }; hidden?: boolean }) {
    const [progress, setProgress] = useState(initial)
    latest = progress
    replaceProgress = setProgress
    useEffect(() => { saveProgress(localStorage, progress) }, [progress])
    return <div hidden={hidden}><LessonCourse initialUnitId={unitId} navigationRequest={navigation} progress={progress} onProgress={update => { writes(); setProgress(update) }} onTerm={() => {}} onPracticeAi={() => {}} /></div>
  }
  const view = render(<Harness />)
  return { writes, progress: () => latest, replace: (value: Progress) => act(() => replaceProgress(value)), rerender: (navigation?: { unitId: string; sequence: number }, hidden = false) => view.rerender(<Harness navigation={navigation} hidden={hidden} />) }
}
async function solve(user: ReturnType<typeof userEvent.setup>, task: MoveTask) {
  const { from, to } = task.solutions[0]
  await user.click(cell(from.x, from.y))
  await user.click(cell(to.x, to.y))
}
async function challenge(user: ReturnType<typeof userEvent.setup>, unit = files) {
  await user.click(screen.getByRole('button', { name: '开始原局面练习' }))
  await solve(user, unit.practice as MoveTask)
  await user.click(screen.getByRole('button', { name: /^(进入未见变式|开始变式复习)$/ }))
}

describe('notation course display and real learning records', { timeout: 30000 }, () => {
  it('keeps the display guide controlled by callbacks with text labels for both sides', async () => {
    const user = userEvent.setup()
    const onFlip = vi.fn()
    const onToggleFiles = vi.fn()
    const storage = vi.spyOn(Storage.prototype, 'setItem')
    const view = render(<NotationLearningGuide orientation="red" showFiles onFlip={onFlip} onToggleFiles={onToggleFiles} />)
    expect(screen.getByRole('rowheader', { name: '红方路数' })).toBeTruthy()
    expect(screen.getByRole('rowheader', { name: '黑方路数' })).toBeTruthy()
    await user.click(flip())
    await user.click(screen.getByRole('button', { name: '隐藏路数辅助' }))
    expect(onFlip).toHaveBeenCalledOnce()
    expect(onToggleFiles).toHaveBeenCalledOnce()
    expect(screen.getByText('当前视角：红方在下')).toBeTruthy()
    view.rerender(<NotationLearningGuide orientation="black" showFiles={false} onFlip={onFlip} onToggleFiles={onToggleFiles} />)
    expect(table()).toBeNull()
    expect(screen.getByRole('button', { name: '显示路数辅助' }).getAttribute('aria-expanded')).toBe('false')
    expect(storage).not.toHaveBeenCalled()
    storage.mockRestore()
  })

  it.each(notationUnits)('shows the new-only guide for $id and accurate classroom size', unit => {
    const course = mountCourse(unit.id)
    expect(screen.getByText('第 7 / 8 章 · 21 个知识点')).toBeTruthy()
    expect(screen.getByRole('region', { name: '棋谱识读辅助' })).toBeTruthy()
    expect(screen.getByText('当前视角：红方在下')).toBeTruthy()
    expect(rows()).toEqual([['九','八','七','六','五','四','三','二','一'], ['1','2','3','4','5','6','7','8','9']])
    expect(course.writes).not.toHaveBeenCalled()
  })

  it.each(['read-notation', 'turns'])('keeps the original %s controls and board unchanged', async unitId => {
    mountCourse(unitId)
    expect(screen.queryByRole('region', { name: '棋谱识读辅助' })).toBeNull()
    expect(cell(4,9).style.left).toBe('50%')
    expect(cell(4,9).style.top).toBe(`${850 / 9}%`)
  })

  it('uses stage defaults, resets on explicit retry, and reverses both labeled rows without changing the demo', async () => {
    const user = userEvent.setup()
    const course = mountCourse()
    const prompt = screen.getByText(files.demo.prompt).textContent
    await user.click(flip())
    expect(screen.getByText('当前视角：黑方在下')).toBeTruthy()
    expect(rows()).toEqual([['一','二','三','四','五','六','七','八','九'], ['9','8','7','6','5','4','3','2','1']])
    expect(cell(8,8).style.left).toBe('5%')
    expect(screen.getByText(files.demo.prompt).textContent).toBe(prompt)
    await user.click(screen.getByRole('button', { name: '演示这一步' }))
    expect(cell(8,5).textContent).toBe('车')
    expect(screen.getByText('当前视角：黑方在下')).toBeTruthy()
    await user.click(screen.getByRole('button', { name: '开始原局面练习' }))
    expect(table()).toBeNull()
    expect(screen.getByText('当前视角：红方在下')).toBeTruthy()
    await user.click(flip())
    await user.click(screen.getByRole('button', { name: '显示路数辅助' }))
    expect(table()).toBeTruthy()
    expect(course.writes).not.toHaveBeenCalled()
    await user.click(screen.getByRole('button', { name: '重试本题' }))
    expect(table()).toBeNull()
    expect(screen.getByText('当前视角：红方在下')).toBeTruthy()
  })

  it('flips only projection and selection, preserving the goal, hints, phase, and all preferences', async () => {
    const user = userEvent.setup()
    const course = mountCourse()
    await challenge(user)
    await user.click(screen.getByRole('button', { name: '提示 1 · 观察' }))
    const before = course.progress()
    localStorage.setItem('unrelated-display-preference', 'keep')
    const storage = { ...localStorage }
    await user.click(cell(6,2))
    expect(cell(6,2).getAttribute('aria-pressed')).toBe('true')
    course.writes.mockClear()
    await user.click(flip())
    expect(cell(6,2).getAttribute('aria-pressed')).toBe('false')
    expect(cell(6,2).textContent).toBe('炮')
    expect(cell(6,2).style.left).toBe('27.5%')
    expect(screen.getByText(files.variants[0].prompt)).toBeTruthy()
    expect(screen.getByText(files.variants[0].hints[0])).toBeTruthy()
    expect(screen.getByText('挑战 · 未见变式')).toBeTruthy()
    expect(course.progress()).toEqual(before)
    expect(course.writes).not.toHaveBeenCalled()
    expect({ ...localStorage }).toEqual(storage)
    expect(table()).toBeNull()
  })

  it('supports black-view native Enter, Space, screen arrows, and Escape without stale selection', async () => {
    const user = userEvent.setup()
    mountCourse()
    await challenge(user)
    await user.click(flip())
    cell(6,2).focus()
    await user.keyboard('{Enter}')
    expect(cell(6,2).getAttribute('aria-pressed')).toBe('true')
    await user.keyboard('{ArrowRight}')
    expect(document.activeElement).toBe(cell(5,2))
    await user.keyboard('{ArrowLeft}{ArrowDown}')
    expect(document.activeElement).toBe(cell(6,1))
    await user.keyboard('{ArrowUp}{Escape}')
    expect(cell(6,2).getAttribute('aria-pressed')).toBe('false')
    await user.keyboard(' ')
    await user.keyboard('{ArrowRight}{ArrowRight}{ArrowRight}{ArrowRight} ')
    expect(status()).toContain('已掌握')
    expect(cell(2,2).textContent).toBe('炮')
    await user.click(flip())
    expect(cell(2,2).textContent).toBe('炮')
    expect(status()).toContain('已掌握')
  })

  it.each(notationUnits)('completes red practice and both-color variants using true goals for $id', async unit => {
    const user = userEvent.setup()
    const course = mountCourse(unit.id)
    await user.click(screen.getByRole('button', { name: '开始原局面练习' }))
    await user.click(flip())
    await solve(user, unit.practice as MoveTask)
    expect(course.progress().practicedUnits).toEqual([unit.id])
    expect(course.progress().masteredUnits).toEqual([])
    await user.click(screen.getByRole('button', { name: '进入未见变式' }))
    expect(table()).toBeNull()
    expect(screen.getByText('当前视角：红方在下')).toBeTruthy()
    await user.click(flip())
    await solve(user, unit.variants[0] as MoveTask)
    expect(course.progress().masteredUnits).toEqual([unit.id])
    expect(course.progress().assistedVariants).toEqual([])
    await user.click(screen.getByRole('button', { name: '换一个未见变式' }))
    await solve(user, unit.variants[1] as MoveTask)
    await user.click(screen.getByRole('button', { name: '换一个未见变式' }))
    await solve(user, unit.variants[2] as MoveTask)
    await user.click(screen.getByRole('button', { name: '换一个变式练习' }))
    expect(screen.getByText('变式练习 · 已见题目')).toBeTruthy()
    expect(table()).toBeNull()
  })

  it('records helper exposure immediately, retains it through hide/retry/flip/reload, then permits a fresh independent variant', async () => {
    const user = userEvent.setup()
    let course = mountCourse()
    await challenge(user)
    await user.click(screen.getByRole('button', { name: '显示路数辅助' }))
    expect(course.progress().assistedVariants).toEqual([files.variants[0].id])
    expect(loadProgress(localStorage).assistedVariants).toEqual([files.variants[0].id])
    await user.click(screen.getByRole('button', { name: '隐藏路数辅助' }))
    await user.click(flip())
    await user.click(screen.getByRole('button', { name: '重试本题' }))
    await solve(user, files.variants[0] as MoveTask)
    expect(course.progress().masteredUnits).toEqual([])
    expect(status()).toContain('只记练习')
    const saved = loadProgress(localStorage)
    cleanup()
    course = mountCourse(files.id, saved)
    await challenge(user)
    expect(screen.getByText(files.variants[1].prompt)).toBeTruthy()
    await user.click(flip())
    await solve(user, files.variants[1] as MoveTask)
    expect(course.progress().masteredUnits).toEqual([files.id])
  })

  it('blocks same-batch helper exposure plus a correct move and never claims false mastery', async () => {
    const user = userEvent.setup()
    const course = mountCourse()
    await challenge(user)
    await user.click(cell(6,2))
    const open = screen.getByRole('button', { name: '显示路数辅助' })
    const target = cell(2,2)
    act(() => { open.click(); target.click() })
    expect(course.progress().assistedVariants).toEqual([files.variants[0].id])
    expect(course.progress().masteredUnits).toEqual([])
    expect(status()).toContain('只记练习')
    expect(status()).not.toContain('已掌握')
    expect(table()).toBeTruthy()
  })

  it('records a first post-answer helper opening without revoking mastery or rewriting the completed result', async () => {
    const user = userEvent.setup()
    const course = mountCourse()
    await challenge(user)
    await solve(user, files.variants[0] as MoveTask)
    const completedResult = status()
    expect(completedResult).toContain('无提示完成未见变式，已掌握')
    expect(course.progress().masteredUnits).toEqual([files.id])
    expect(course.progress().assistedVariants).toEqual([])
    await user.click(screen.getByRole('button', { name: '显示路数辅助' }))
    expect(table()).toBeTruthy()
    expect(course.progress().assistedVariants).toEqual([files.variants[0].id])
    expect(loadProgress(localStorage).assistedVariants).toEqual([files.variants[0].id])
    expect(course.progress().masteredUnits).toEqual([files.id])
    expect(status()).toBe(completedResult)
    expect(screen.queryByText('本题只记练习，掌握需要另一个未曝光变式。')).toBeNull()
    await user.click(screen.getByRole('button', { name: '隐藏路数辅助' }))
    await user.click(flip())
    expect(status()).toBe(completedResult)
    await user.click(screen.getByRole('button', { name: '重试本题' }))
    expect(screen.getByText('变式练习 · 已见题目')).toBeTruthy()
    expect(table()).toBeNull()
    await solve(user, files.variants[0] as MoveTask)
    expect(status()).toContain('只记练习')
    expect(course.progress().masteredUnits).toEqual([files.id])
    expect(course.progress().assistedVariants).toEqual([files.variants[0].id])
    const saved = loadProgress(localStorage)
    cleanup()
    const refreshed = mountCourse(files.id, saved)
    expect(refreshed.progress().assistedVariants).toEqual([files.variants[0].id])
    expect(refreshed.progress().masteredUnits).toEqual([files.id])
    await challenge(user)
    expect(screen.getByText(files.variants[1].prompt)).toBeTruthy()
  })

  it('keeps completed independent feedback when later exposure is reflected in Progress', async () => {
    const user = userEvent.setup()
    const course = mountCourse()
    await challenge(user)
    await solve(user, files.variants[0] as MoveTask)
    const completedResult = status()
    course.replace({ ...course.progress(), assistedVariants: [files.variants[0].id] })
    expect(course.progress().masteredUnits).toEqual([files.id])
    expect(status()).toBe(completedResult)
    expect(status()).not.toContain('只记练习')
    expect(screen.queryByText('本题只记练习，掌握需要另一个未曝光变式。')).toBeNull()
  })

  it('uses the latest replacement Progress for both challenge grading and feedback', async () => {
    const user = userEvent.setup()
    const course = mountCourse()
    await challenge(user)
    course.replace({ ...course.progress(), assistedVariants: [files.variants[0].id] })
    await solve(user, files.variants[0] as MoveTask)
    expect(course.progress().masteredUnits).toEqual([])
    expect(status()).toContain('只记练习')
  })

  it('enters review with the helper hidden when all three variants were exposed in saved Progress', async () => {
    const user = userEvent.setup()
    const initial = { ...defaultProgress(), assistedVariants: files.variants.map(task => task.id) }
    const course = mountCourse(files.id, initial)
    await challenge(user)
    expect(screen.getByText('变式练习 · 已见题目')).toBeTruthy()
    expect(screen.queryByRole('button', { name: /未见变式/ })).toBeNull()
    expect(table()).toBeNull()
    await user.click(screen.getByRole('button', { name: '显示路数辅助' }))
    expect(course.progress().assistedVariants).toEqual(initial.assistedVariants)
    await user.click(screen.getByRole('button', { name: '隐藏路数辅助' }))
    await solve(user, files.variants[0] as MoveTask)
    expect(status()).toContain('只记练习')
    expect(course.progress().masteredUnits).toEqual([])
  })

  it('preserves display on rerenders/hidden panels, resets it on navigation, and keeps visited variants seen', async () => {
    const user = userEvent.setup()
    const course = mountCourse()
    await challenge(user)
    await user.click(screen.getByRole('button', { name: '显示路数辅助' }))
    await user.click(screen.getByRole('button', { name: '提示 1 · 观察' }))
    await user.click(flip())
    await user.click(cell(6,2))
    course.rerender(undefined, true)
    course.rerender()
    expect(screen.getByText('当前视角：黑方在下')).toBeTruthy()
    expect(table()).toBeTruthy()
    expect(cell(6,2).getAttribute('aria-pressed')).toBe('true')
    expect(screen.getByText(files.variants[0].hints[0])).toBeTruthy()
    course.rerender({ unitId: notationUnits[1].id, sequence: 1 })
    expect(screen.getByText('当前视角：红方在下')).toBeTruthy()
    expect(table()).toBeTruthy()
    course.rerender({ unitId: files.id, sequence: 2 })
    expect(cell(8,8).getAttribute('aria-pressed')).toBe('false')
    expect(screen.queryByText(files.variants[0].hints[0])).toBeNull()
    await challenge(user)
    expect(screen.getByText(files.variants[1].prompt)).toBeTruthy()
    await user.click(screen.getByRole('button', { name: '换一个未见变式' }))
    await user.click(screen.getByRole('button', { name: '换一个变式练习' }))
    expect(screen.getByText('变式练习 · 已见题目')).toBeTruthy()
    await user.click(screen.getByRole('button', { name: '显示路数辅助' }))
    expect(course.progress().assistedVariants).toContain(files.variants[0].id)
  })

  it('resets a successfully restored classroom instance from its normal demo entry', async () => {
    const user = userEvent.setup()
    const course = mountCourse()
    await challenge(user)
    await user.click(screen.getByRole('button', { name: '显示路数辅助' }))
    await user.click(flip())
    const saved = course.progress()
    cleanup()
    const restored = mountCourse(files.id, saved)
    expect(screen.getByText('演示 · 先看一遍')).toBeTruthy()
    expect(screen.getByText('当前视角：红方在下')).toBeTruthy()
    expect(table()).toBeTruthy()
    expect(restored.progress().assistedVariants).toEqual([files.variants[0].id])
  })

  it('distinguishes illegal and legal off-target moves while friendly reselect/cancel submits nothing', async () => {
    const user = userEvent.setup()
    const course = mountCourse()
    await user.click(screen.getByRole('button', { name: '开始原局面练习' }))
    await user.click(cell(8,8))
    await user.click(cell(2,6))
    expect(status()).not.toContain('不能走到这里')
    expect(cell(2,6).getAttribute('aria-pressed')).toBe('true')
    fireEvent.keyDown(cell(2,6), { key: 'Escape' })
    await user.click(cell(8,8))
    await user.click(cell(7,7))
    expect(status()).toContain('不能走到这里')
    await user.click(cell(8,7))
    expect(status()).toContain('合法，但与本题要求')
    expect(cell(8,8).textContent).toBe('车')
    expect(course.writes).not.toHaveBeenCalled()
    fireEvent.keyDown(cell(8,8), { key: 'Escape' })
    await solve(user, files.practice as MoveTask)
    expect(course.progress().practicedUnits).toEqual([files.id])
  })
})
