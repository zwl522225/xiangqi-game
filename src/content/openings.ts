import type { Move } from '../core/types'

export type OpeningStep = {
  move: Move
  note: string
  intent: string
  hints: [string, string, string]
}
export type Opening = { id: string; version: number; title: string; summary: string; steps: OpeningStep[] }

const step = (
  fx: number, fy: number, tx: number, ty: number,
  note: string, intent: string, pieceHint: string, targetHint: string,
): OpeningStep => ({
  move: { from: { x: fx, y: fy }, to: { x: tx, y: ty } },
  note, intent, hints: [intent, pieceHint, targetHint],
})

